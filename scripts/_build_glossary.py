# English non-nouns only (no common nouns). UI verbs included because screenshots
# often OCR a single button/label such as Save / Cancel / Next.
EN_JA: dict[str, str] = {}


def add(pairs: dict[str, str]) -> None:
    for en, ja in pairs.items():
        key = en.strip()
        if not key:
            continue
        EN_JA[key] = ja


